		private static void DecreaseReferenceCount(UIntPtr nativePtr)
		{
			var iManaged = _iManaged.GetValue(null);
			_decreaseReferenceCount.Invoke(iManaged, new object[] { nativePtr });
		}

		public static MetaMesh CreateMetaMeshFromPointer(IntPtr metaMeshPtr)
		{
			if (metaMeshPtr == IntPtr.Zero)
				throw new ArgumentNullException("metaMeshPtr cannot be null");

			return (MetaMesh)_metaMeshConstructor.Invoke(new object[] { I2U(metaMeshPtr) });
		}

		public static void GetHeadMetaMeshOfVisuals([NotNull] this MBAgentVisuals visuals, 
			[CanBeNull] out MetaMesh head,
			[CanBeNull] out MetaMesh bread,
			[CanBeNull] out MetaMesh hair,
			[CanBeNull] out MetaMesh eyebrow,
			bool immediatelyInvalidate = false)
		{
			if (visuals == null)
				throw new ArgumentNullException(nameof(visuals));

			head = null;
			bread = null;
			hair = null;
			eyebrow = null;

			var skeleton = visuals.GetSkeleton();
			var comp = _getComponentAtIndexDelegate.DynamicInvoke(
				(UIntPtr)_getPointer.GetValue(skeleton), GameEntity.ComponentType.CustomType1, 0);
			var uIntPtr = GetNativeObjectPointer(comp);

			if (uIntPtr != UIntPtr.Zero)
			{
				const int BASE_OFFSET = 256;
				var intPtr = U2I(uIntPtr);
				var headPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET);
				var breadPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET + 8);
				var hairPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET + 16);
				var eyebrowPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET + 24);

				if (headPtr != IntPtr.Zero && head == null)
				{
					head = NativeUtil.CreateMetaMeshFromPointer(headPtr);
				}

				if (breadPtr != IntPtr.Zero && bread == null)
				{
					bread = NativeUtil.CreateMetaMeshFromPointer(breadPtr);
				}

				if (hairPtr != IntPtr.Zero && hair == null)
				{
					hair = NativeUtil.CreateMetaMeshFromPointer(hairPtr);
				}

				if (eyebrowPtr != IntPtr.Zero && eyebrow == null)
				{
					eyebrow = NativeUtil.CreateMetaMeshFromPointer(eyebrowPtr);
				}

				if (immediatelyInvalidate)
				{
					head?.ManualInvalidate();
					bread?.ManualInvalidate();
					hair?.ManualInvalidate();
					eyebrow?.ManualInvalidate();
				}

				DecreaseReferenceCount(uIntPtr);
			}
		}

		public static long GetLowerbodyEnforcementMasks(Skeleton skeleton)
		{
			// was 432 in 1.5.6
			const int BASE_OFFSET_FOR_SKELETON_MODEL = 424;
			const int BASE_OFFSET_FOR_ENFORCEMENT_MASKS = 336;

			var uIntPtr = (UIntPtr) _getPointer.GetValue(skeleton);

			if (uIntPtr != UIntPtr.Zero)
			{
				var intPtr = U2I(uIntPtr);
				var skeletonModelPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET_FOR_SKELETON_MODEL);
				var mask = Marshal.ReadInt64(skeletonModelPtr, BASE_OFFSET_FOR_ENFORCEMENT_MASKS);
				return mask;
			}

			return -1;
		}

		public static void SetLowerbodyEnforcementMasks(Skeleton skeleton, long masks)
		{
			const int BASE_OFFSET_FOR_SKELETON_MODEL = 424;
			const int BASE_OFFSET_FOR_ENFORCEMENT_MASKS = 336;

			var uIntPtr = (UIntPtr) _getPointer.GetValue(skeleton);

			if (uIntPtr != UIntPtr.Zero)
			{
				var intPtr = U2I(uIntPtr);
				var skeletonModelPtr = Marshal.ReadIntPtr(intPtr, BASE_OFFSET_FOR_SKELETON_MODEL);
				Marshal.WriteInt64(skeletonModelPtr, BASE_OFFSET_FOR_ENFORCEMENT_MASKS, masks);
			}
		}

