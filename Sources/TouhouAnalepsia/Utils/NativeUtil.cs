		[InitOnSubModuleLoad]
		public static void Init()
		{
			_getPointer = typeof(NativeObject).GetField("_pointer", BindingFlags.Instance | BindingFlags.NonPublic);

			_metaMeshConstructor = typeof(MetaMesh).GetConstructor(BindingFlags.NonPublic | BindingFlags.Instance, null,
				new[] {typeof(UIntPtr)}, null);

			_gameEntityConstructor = typeof(GameEntity).GetConstructor(BindingFlags.NonPublic | BindingFlags.Instance, null,
				new[] { typeof(UIntPtr) }, null);

			FieldInfo field = GetFieldOfNonPublicClass(
				"TaleWorlds.Engine.AutoGenerated, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"ManagedCallbacks.ScriptingInterfaceOfISkeleton",
				"call_GetComponentAtIndexDelegate", BindingFlags.Public | BindingFlags.Static);
			_getComponentAtIndexDelegate = field.GetValue(null) as Delegate;

			_iManaged = GetFieldOfNonPublicClass(
				"TaleWorlds.DotNet, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"TaleWorlds.DotNet.LibraryApplicationInterface",
				"IManaged", BindingFlags.NonPublic | BindingFlags.Static);

			_nativeObjectPointer = GetFieldOfNonPublicClass(
				"TaleWorlds.DotNet, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"TaleWorlds.DotNet.NativeObjectPointer",
				"Pointer", BindingFlags.Public | BindingFlags.Instance);

			_decreaseReferenceCount = GetInterfaceMethodOfNonPublicClass(
				"TaleWorlds.DotNet, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"TaleWorlds.DotNet.IManaged",
				"DecreaseReferenceCount", BindingFlags.Public | BindingFlags.Instance);

			var typeId = GetFieldOfNonPublicClass(
				"TaleWorlds.DotNet, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"TaleWorlds.DotNet.EngineClassTypeDefinition",
				"TypeId", BindingFlags.Public | BindingFlags.Instance);

			var typeName = GetFieldOfNonPublicClass(
				"TaleWorlds.DotNet, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
				"TaleWorlds.DotNet.EngineClassTypeDefinition",
				"TypeName", BindingFlags.Public | BindingFlags.Instance);

			var _nativeObjectInfoes = typeof(NativeObject).GetField(
				"_typeDefinitions", BindingFlags.NonPublic | BindingFlags.Static);
			var daze = _nativeObjectInfoes.GetValue(null) as IList;
			for (var i = 0; i < daze.Count; i++)
			{
				object info = daze[i];
				var name = typeName.GetValue(info) as string;
				if (name == "rglEntity_component")
				{
					_faceMeshComponentId = (int) typeId.GetValue(info);
					break;
				}
			}
		}

		private static FieldInfo GetFieldOfNonPublicClass(string assemblyFullName, string className,
			string fieldName, BindingFlags bindingFlags)
		{
			var assembly = Assembly.Load(assemblyFullName);
			var klass = assembly.GetType(className);
			var field = klass.GetField(fieldName, bindingFlags);
			return field;
		}

		private static MethodInfo GetInterfaceMethodOfNonPublicClass(string assemblyFullName, string className,
			string methodName, BindingFlags bindingFlags)
		{
			var assembly = Assembly.Load(assemblyFullName);
			var klass = assembly.GetType(className);
			var method = klass.GetMethod(methodName, bindingFlags);
			return method;
		}

